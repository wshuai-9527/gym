const line = (a, color, width = 5) =>
  `<line x1="${a[0]}" y1="${a[1]}" x2="${a[2]}" y2="${a[3]}" stroke="${color}" stroke-width="${width}" stroke-linecap="round"/>`;
function pose(base, limbs, equipment) {
  let support = line([5, 108, 130, 108], "#cbd5df", 2);
  if (["bench", "seat", "support"].includes(equipment))
    support += line([28, 76, 100, 76], "#94a3b8", 4);
  if (equipment === "incline") support += line([22, 34, 77, 87], "#94a3b8", 4);
  if (equipment === "split") support += line([103, 66, 130, 66], "#94a3b8", 4);
  if (equipment === "cable") support += line([25, 4, 105, 4], "#94a3b8", 4);
  const head = base[0];
  return (
    support +
    `<circle cx="${head[0]}" cy="${head[1]}" r="8" fill="#172334"/>` +
    base.map((x) => line(x, "#172334")).join("") +
    limbs.map((x) => line(x, "#0b8074")).join("")
  );
}
